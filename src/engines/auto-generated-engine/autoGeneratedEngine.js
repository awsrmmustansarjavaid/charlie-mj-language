export function pickAutoGeneratedTrack(tracks, source) {
  const l = String(source || 'auto')
    .split('-')[0]
    .toLowerCase();
  return (
    (tracks || []).find(
      (t) =>
        t.kind === 'asr' &&
        (!l ||
          String(t.languageCode || '')
            .split('-')[0]
            .toLowerCase() === l)
    ) ||
    (tracks || []).find((t) => t.kind === 'asr') ||
    null
  );
}
